#[derive(Debug)]
struct ApiError {
    status: StatusCode,
    code: &'static str,
    message: String,
}

impl IntoResponse for ApiError {
    fn into_response(self) -> Response {
        // messages are generated by the engine from metadata only: they never contain request text
        (self.status, axum::Json(json!({"error": {"code": self.code, "message": self.message}}))).into_response()
    }
}

impl From<DlpError> for ApiError {
    fn from(e: DlpError) -> Self {
        let (status, code) = match &e {
            DlpError::InvalidInput(_) => (StatusCode::BAD_REQUEST, "invalid_input"),
            DlpError::TooLarge(_) => (StatusCode::PAYLOAD_TOO_LARGE, "too_large"),
            DlpError::DetectorUnavailable(_) => (StatusCode::SERVICE_UNAVAILABLE, "detector_unavailable"),
            DlpError::Timeout(_) => (StatusCode::GATEWAY_TIMEOUT, "timeout"),
            DlpError::Rules(_) => (StatusCode::UNPROCESSABLE_ENTITY, "rules_invalid"),
            DlpError::Storage(_) => (StatusCode::INTERNAL_SERVER_ERROR, "storage_error"),
            DlpError::Policy(_) => (StatusCode::UNPROCESSABLE_ENTITY, "policy_error"),
            DlpError::Vault(_) => (StatusCode::BAD_REQUEST, "vault_error"),
            DlpError::Forbidden(_) => (StatusCode::FORBIDDEN, "forbidden"),
            DlpError::NotFound(_) => (StatusCode::NOT_FOUND, "not_found"),
            DlpError::Internal(_) => (StatusCode::INTERNAL_SERVER_ERROR, "internal_error"),
        };
        ApiError { status, code, message: e.to_string() }
    }
}

fn bad(msg: &str) -> ApiError {
    ApiError { status: StatusCode::BAD_REQUEST, code: "invalid_input", message: msg.to_string() }
}

struct Authed(Caller);

#[axum::async_trait]
impl FromRequestParts<S> for Authed {
    type Rejection = ApiError;
    async fn from_request_parts(parts: &mut Parts, state: &S) -> Result<Self, ApiError> {
        let presented = bearer(&parts.headers);
        match state.auth.authenticate(presented.as_deref()) {
            Some(c) => Ok(Authed(c)),
            None => Err(ApiError { status: StatusCode::UNAUTHORIZED, code: "unauthorized", message: "missing or invalid API key".into() }),
        }
    }
}

fn bearer(h: &HeaderMap) -> Option<String> {
    if let Some(v) = h.get(header::AUTHORIZATION).and_then(|v| v.to_str().ok()) {
        if let Some(t) = v.strip_prefix("Bearer ") {
            return Some(t.trim().to_string());
        }
    }
    h.get("x-api-key").and_then(|v| v.to_str().ok()).map(|s| s.trim().to_string())
}

/// Run blocking engine work off the async runtime, bounded by the in-flight limit (load shedding).
async fn run<T: Send + 'static>(st: &S, f: impl FnOnce() -> Result<T, DlpError> + Send + 'static) -> Result<T, ApiError> {
    let permit = st.inflight.clone().try_acquire_owned().map_err(|_| {
        st.shed.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        ApiError { status: StatusCode::SERVICE_UNAVAILABLE, code: "overloaded", message: "too many requests in flight".into() }
    })?;
    let r = tokio::task::spawn_blocking(move || {
        let _p = permit;
        f()
    })
    .await
    .map_err(|_| ApiError { status: StatusCode::INTERNAL_SERVER_ERROR, code: "internal_error", message: "worker panicked (isolated)".into() })?;
    r.map_err(ApiError::from)
}

fn parse<T: for<'de> Deserialize<'de>>(b: &Bytes) -> Result<T, ApiError> {
    serde_json::from_slice(b).map_err(|e| bad(&format!("invalid JSON body: {}", e.classify_str())))
}
trait ClassifyStr {
    fn classify_str(&self) -> &'static str;
}
impl ClassifyStr for serde_json::Error {
    fn classify_str(&self) -> &'static str {
        match self.classify() {
            serde_json::error::Category::Syntax => "syntax error",
            serde_json::error::Category::Data => "unexpected structure or type",
            serde_json::error::Category::Eof => "unexpected end of input",
            serde_json::error::Category::Io => "io error",
        }
    }
}

use dlp_engine::api_json::{run_body, to_request as engine_to_request, Body};

fn check_tenant(c: &Caller, b: &Body) -> Result<(), ApiError> {
    if let Some(t) = &b.tenant_id {
        if t != &c.tenant_id {
            return Err(ApiError { status: StatusCode::FORBIDDEN, code: "tenant_mismatch", message: "tenant_id in the body does not match the authenticated tenant".into() });
        }
    }
    Ok(())
}

fn to_request(b: &Body, forced: Option<Mode>) -> Result<DetectRequest, ApiError> {
    engine_to_request(b, forced).map_err(ApiError::from)
}

async fn handle_detect(st: &S, c: Caller, body: Bytes, forced: Option<Mode>) -> Result<Response, ApiError> {
    let b: Body = parse(&body)?;
    check_tenant(&c, &b)?;
    let engine = st.engine.clone();
    let r = run(st, move || run_body(&engine, &c, &b, forced)).await?;
    Ok(axum::Json(r).into_response())
}

async fn detect(State(st): State<S>, Authed(c): Authed, body: Bytes) -> Result<Response, ApiError> {
    handle_detect(&st, c, body, None).await
}
async fn sanitize(State(st): State<S>, Authed(c): Authed, body: Bytes) -> Result<Response, ApiError> {
    handle_detect(&st, c, body, Some(Mode::Sanitize)).await
}
async fn anonymize(State(st): State<S>, Authed(c): Authed, body: Bytes) -> Result<Response, ApiError> {
    handle_detect(&st, c, body, Some(Mode::Anonymize)).await
}

#[derive(Deserialize)]
struct DeanonBody {
    session_id: String,
    text: String,
    direction: Option<String>,
    policy_id: Option<String>,
    check_response: Option<bool>,
    tenant_id: Option<String>,
}

async fn deanonymize(State(st): State<S>, Authed(c): Authed, body: Bytes) -> Result<Response, ApiError> {
    let b: DeanonBody = parse(&body)?;
    if b.tenant_id.as_ref().map(|t| t != &c.tenant_id).unwrap_or(false) {
        return Err(ApiError { status: StatusCode::FORBIDDEN, code: "tenant_mismatch", message: "tenant_id in the body does not match the authenticated tenant".into() });
    }
    let dir = b.direction.as_deref().map(|d| Direction::parse(d).ok_or_else(|| bad("bad direction"))).transpose()?.unwrap_or(Direction::Response);
    let engine = st.engine.clone();
    let r = run(&st, move || engine.deanonymize(&c, &b.session_id, &b.text, dir, b.policy_id.as_deref(), b.check_response.unwrap_or(true))).await?;
    Ok(axum::Json(r).into_response())
}

#[derive(Deserialize)]
struct BatchBody {
    items: Vec<Body>,
    policy_id: Option<String>,
    mode: Option<String>,
    tenant_id: Option<String>,
}

async fn detect_batch(State(st): State<S>, Authed(c): Authed, body: Bytes) -> Result<Response, ApiError> {
    let b: BatchBody = parse(&body)?;
    if b.tenant_id.as_ref().map(|t| t != &c.tenant_id).unwrap_or(false) {
        return Err(ApiError { status: StatusCode::FORBIDDEN, code: "tenant_mismatch", message: "tenant_id mismatch".into() });
    }
    if b.items.len() > st.engine.cfg.limits.max_batch {
        return Err(DlpError::TooLarge(format!("batch of {} exceeds limit {}", b.items.len(), st.engine.cfg.limits.max_batch)).into());
    }
    let mut reqs = Vec::with_capacity(b.items.len());
    for mut it in b.items {
        check_tenant(&c, &it)?;
        if it.policy_id.is_none() {
            it.policy_id = b.policy_id.clone();
        }
        if it.mode.is_none() {
            it.mode = b.mode.clone();
        }
        reqs.push(to_request(&it, None)?);
    }
    let engine = st.engine.clone();
    let results = run(&st, move || Ok(engine.process_many(&c, &reqs))).await?;
    let out: Vec<Value> = results
        .into_iter()
        .map(|r| match r {
            Ok(v) => json!({"ok": true, "result": v}),
            Err(e) => {
                let a = ApiError::from(e);
                json!({"ok": false, "error": {"code": a.code, "message": a.message}})
            }
        })
        .collect();
    Ok(axum::Json(json!({"results": out})).into_response())
}

