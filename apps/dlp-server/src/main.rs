fn main() {
    let args = Args::parse();
    if let Some(Sub::Genkey) = args.cmd {
        use rand::RngCore;
        use sha2::{Digest, Sha256};
        let mut b = [0u8; 32];
        rand::thread_rng().fill_bytes(&mut b);
        let key = format!("dlp_{}", hex::encode(b));
        println!("API key (shown once): {key}");
        println!("key_sha256: {}", hex::encode(Sha256::digest(key.as_bytes())));
        return;
    }
    let auth = match (&args.api_keys, args.insecure_no_auth) {
        (Some(p), _) => Auth::from_file(p).unwrap_or_else(|e| fatal(&format!("api keys: {e}"))),
        (None, true) => {
            let addr = args.listen.to_lowercase();
            if !(addr.starts_with("127.") || addr.starts_with("localhost") || addr.starts_with("[::1]")) {
                fatal("--insecure-no-auth is only allowed on loopback addresses");
            }
            eprintln!("WARNING: authentication disabled (--insecure-no-auth); every caller is tenant 'dev' with all scopes");
            Auth::insecure()
        }
        (None, false) => fatal("authentication is required: pass --api-keys <file> (see `dlp-server genkey`), or --insecure-no-auth on loopback for development"),
    };
    let mut cfg = EngineConfig::default();
    cfg.db_path = args.db.clone();
    cfg.rules_dir = Some(args.rules_dir.clone());
    cfg.use_hyperscan = !args.no_hyperscan;
    cfg.default_policy = args.default_policy.clone();
    cfg.vault.ttl = Duration::from_secs(args.vault_ttl_secs);
    cfg.vault.nonce_placeholders = args.nonce_placeholders;
    cfg.limits.max_text_bytes = args.max_text_bytes;
    cfg.limits.request_timeout = Duration::from_secs(args.request_timeout_secs);
    cfg.limits.nlp_max_bytes = args.nlp_max_bytes;
    if let Some(u) = &args.nlp_url {
        cfg.nlp = Some(NlpConfig { base_url: u.trim_end_matches('/').to_string(), token: args.nlp_token.clone(), ..Default::default() });
    }
    let engine = DlpEngine::open(cfg).unwrap_or_else(|e| fatal(&format!("engine: {e}")));
    if args.audit_log {
        engine.set_audit_hook(Arc::new(|ev| {
            if let Ok(s) = serde_json::to_string(ev) {
                eprintln!("AUDIT {s}");
            }
        }));
    }
    let rt = tokio::runtime::Builder::new_multi_thread().enable_all().max_blocking_threads(args.max_inflight.max(8)).build().unwrap();
    rt.block_on(async move {
        let state: S = Arc::new(AppState { engine: engine.clone(), auth, inflight: Arc::new(Semaphore::new(args.max_inflight)), streams: Mutex::new(HashMap::new()), shed: Default::default() });
        // background maintenance: vault expiry + optional rule watcher
        let e2 = engine.clone();
        tokio::spawn(async move {
            let mut t = tokio::time::interval(Duration::from_secs(30));
            loop {
                t.tick().await;
                let e = e2.clone();
                let _ = tokio::task::spawn_blocking(move || e.vault.sweep()).await;
            }
        });
        if args.watch_rules_secs > 0 {
            let e3 = engine.clone();
            let every = args.watch_rules_secs;
            tokio::spawn(async move {
                let mut t = tokio::time::interval(Duration::from_secs(every));
                loop {
                    t.tick().await;
                    let e = e3.clone();
                    match tokio::task::spawn_blocking(move || e.reload_if_changed()).await {
                        Ok(Ok(Some(r))) => eprintln!("rules reloaded: v{} ({} rules)", r.ruleset_version, r.rules_enabled),
                        Ok(Err(err)) => eprintln!("rules reload REJECTED, previous rule set kept: {err}"),
                        _ => {}
                    }
                }
            });
        }
        let body_limit = args.max_text_bytes * 2 + 4096;
        let app = Router::new()
            .route("/health", get(health))
            .route("/metrics", get(metrics))
            .route("/openapi.yaml", get(openapi))
            .route("/v1/capabilities", get(capabilities))
            .route("/v1/detect", post(detect))
            .route("/v1/sanitize", post(sanitize))
            .route("/v1/anonymize", post(anonymize))
            .route("/v1/deanonymize", post(deanonymize))
            .route("/v1/detect/batch", post(detect_batch))
            .route("/v1/scan/stream", post(scan_stream))
            .route("/v1/rules/reload", post(reload))
            .route("/v1/rules/rollback", post(rollback))
            .route("/v1/rules/versions", get(rule_versions))
            .layer(DefaultBodyLimit::max(body_limit))
            .with_state(state);
        let listener = tokio::net::TcpListener::bind(&args.listen).await.unwrap_or_else(|e| fatal(&format!("bind {}: {e}", args.listen)));
        eprintln!("dlp-server listening on http://{} (ruleset v{}, {} rules)", args.listen, engine.ruleset().version, engine.ruleset().rule_count());
        axum::serve(listener, app).with_graceful_shutdown(async {
            let _ = tokio::signal::ctrl_c().await;
        })
        .await
        .unwrap();
    });
}

fn fatal(m: &str) -> ! {
    eprintln!("error: {m}");
    std::process::exit(2)
}
