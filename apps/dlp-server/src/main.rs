async fn rule_versions(State(st): State<S>, Authed(c): Authed) -> Result<Response, ApiError> {
    if !c.has_scope("rules:reload") {
        return Err(DlpError::Forbidden("missing scope 'rules:reload'".into()).into());
    }
    let engine = st.engine.clone();
    let v = run(&st, move || engine.store.list_versions().map_err(|e| DlpError::Storage(e.to_string()))).await?;
    Ok(axum::Json(json!({"versions": v})).into_response())
}

async fn health(State(st): State<S>) -> Response {
    // unauthenticated, minimal: liveness + coarse readiness only
    let statuses = st.engine.detector_statuses();
    let nlp_expected = statuses.iter().any(|s| s.name == "presidio");
    let nlp_ready = statuses.iter().filter(|s| s.name == "presidio").all(|s| s.state == DetectorState::Ready);
    let status = if !nlp_expected || nlp_ready { "ok" } else { "degraded" };
    axum::Json(json!({"status": status, "ruleset_version": st.engine.ruleset().version})).into_response()
}

async fn capabilities(State(st): State<S>, Authed(_c): Authed) -> Result<Response, ApiError> {
    let engine = st.engine.clone();
    let mut v = run(&st, move || {
        let mut v = engine.capabilities();
        v["nlp"] = engine.nlp_status().unwrap_or(json!({"state": "unreachable_or_not_configured"}));
        let rs = engine.ruleset();
        v["streaming"] = json!({"window_mode_available": rs.window_bound_all().is_some(), "window_bound_bytes": rs.window_bound_all(), "window_blockers": rs.window_blockers()});
        Ok(v)
    })
    .await?;
    v["auth"] = json!({"insecure_no_auth": st.auth.insecure});
    Ok(axum::Json(v).into_response())
}

async fn metrics(State(st): State<S>, Authed(c): Authed) -> Result<Response, ApiError> {
    if !c.has_scope("metrics") {
        return Err(DlpError::Forbidden("missing scope 'metrics'".into()).into());
    }
    use std::sync::atomic::Ordering::Relaxed;
    let e = &st.engine;
    let mut s = String::new();
    let mut put = |name: &str, help: &str, v: f64, labels: &str| {
        s.push_str(&format!("# HELP {name} {help}\n# TYPE {name} counter\n{name}{labels} {v}\n"));
    };
    put("dlp_requests_total", "processed detection requests", e.counters.requests.load(Relaxed) as f64, "");
    put("dlp_blocked_total", "requests with decision=blocked", e.counters.blocked.load(Relaxed) as f64, "");
    put("dlp_modified_total", "requests with decision=modified", e.counters.modified.load(Relaxed) as f64, "");
    put("dlp_degraded_total", "requests where an enabled detector could not run", e.counters.degraded.load(Relaxed) as f64, "");
    put("dlp_errors_total", "requests failed with an error", e.counters.errors.load(Relaxed) as f64, "");
    put("dlp_entities_total", "entities reported", e.counters.entities.load(Relaxed) as f64, "");
    put("dlp_rule_reloads_total", "successful rule reloads", e.counters.reloads_ok.load(Relaxed) as f64, "");
    put("dlp_rule_reload_failures_total", "rejected rule reloads (old rule set kept)", e.counters.reloads_failed.load(Relaxed) as f64, "");
    put("dlp_shed_total", "requests rejected by the in-flight limit", st.shed.load(Relaxed) as f64, "");
    put("dlp_processing_seconds_total", "cumulative processing time", e.counters.total_us.load(Relaxed) as f64 / 1e6, "");
    for (name, m) in e.detector_metrics() {
        let l = format!("{{detector=\"{name}\"}}");
        put("dlp_detector_calls_total", "detector invocations", m.calls as f64, &l);
        put("dlp_detector_errors_total", "detector failures", m.errors as f64, &l);
        put("dlp_detector_seconds_total", "cumulative detector time", m.total_us as f64 / 1e6, &l);
    }
    s.push_str(&format!("# TYPE dlp_ruleset_version gauge\ndlp_ruleset_version {}\n# TYPE dlp_rules_enabled gauge\ndlp_rules_enabled {}\n# TYPE dlp_vault_sessions gauge\ndlp_vault_sessions {}\n# TYPE dlp_uptime_seconds gauge\ndlp_uptime_seconds {}\n", e.ruleset().version, e.ruleset().rule_count(), e.vault.session_count(), e.started.elapsed().as_secs()));
    for d in e.detector_statuses() {
        s.push_str(&format!("dlp_detector_ready{{detector=\"{}\"}} {}\n", d.name, (d.state == DetectorState::Ready) as u8));
    }
    let mut r = (StatusCode::OK, s).into_response();
    r.headers_mut().insert(header::CONTENT_TYPE, HeaderValue::from_static("text/plain; version=0.0.4"));
    Ok(r)
}

