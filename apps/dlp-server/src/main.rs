/// POST /v1/scan/stream
///  * `Content-Type: text/event-stream` (or text/plain): body is a complete upstream SSE stream; the
///    response is the scanned/sanitized SSE stream (`X-DLP-Blocked: 1` when blocked).
///  * `Content-Type: application/json`: incremental protocol for proxies: send chunks with a
///    `stream_id` and `final: true` on the last one; each reply carries the bytes that may be forwarded.
async fn scan_stream(State(st): State<S>, Authed(c): Authed, Query(q): Query<StreamQuery>, headers: HeaderMap, body: Bytes) -> Result<Response, ApiError> {
    let ct = headers.get(header::CONTENT_TYPE).and_then(|v| v.to_str().ok()).unwrap_or("").to_ascii_lowercase();
    let engine = st.engine.clone();
    if ct.starts_with("application/json") {
        let b: StreamJson = parse(&body)?;
        if b.tenant_id.as_ref().map(|t| t != &c.tenant_id).unwrap_or(false) {
            return Err(ApiError { status: StatusCode::FORBIDDEN, code: "tenant_mismatch", message: "tenant_id mismatch".into() });
        }
        if b.stream_id.is_empty() || b.stream_id.len() > 128 {
            return Err(bad("stream_id must be 1-128 chars"));
        }
        let chunk: Vec<u8> = match (&b.chunk, &b.chunk_b64) {
            (Some(t), _) => t.clone().into_bytes(),
            (None, Some(x)) => base64::engine::general_purpose::STANDARD.decode(x).map_err(|_| bad("chunk_b64 is not valid base64"))?,
            _ => vec![],
        };
        let key = (c.tenant_id.clone(), b.stream_id.clone());
        let stt = st.clone();
        let opts = StreamOptions { policy_id: b.policy_id.clone(), session_id: b.session_id.clone(), anonymize: b.anonymize.unwrap_or(false), mode: b.mode.clone(), ..Default::default() };
        let is_final = b.is_final;
        let r = run(&st, move || {
            let mut map = stt.streams.lock();
            // expire idle streams so abandoned ones cannot pin memory
            map.retain(|_, e| e.last.elapsed() < Duration::from_secs(300));
            if !map.contains_key(&key) {
                if map.len() >= 1024 {
                    return Err(DlpError::TooLarge("too many concurrent streams".into()));
                }
                let s = engine.open_stream(&c, &opts)?;
                map.insert(key.clone(), StreamEntry { stream: s, last: Instant::now() });
            }
            let e = map.get_mut(&key).unwrap();
            e.last = Instant::now();
            let mut out = e.stream.push(&chunk);
            if is_final {
                out.extend(e.stream.finish());
            }
            let blocked = e.stream.is_blocked();
            let stats = serde_json::to_value(e.stream.stats()).unwrap_or(Value::Null);
            let done = is_final || blocked;
            if done {
                map.remove(&key);
            }
            Ok((out, blocked, done, stats))
        })
        .await?;
        let (out, blocked, done, stats) = r;
        return Ok(axum::Json(json!({"output": String::from_utf8_lossy(&out), "blocked": blocked, "finished": done, "stats": stats})).into_response());
    }
    // whole-stream mode
    let opts = StreamOptions { policy_id: q.policy_id.clone(), session_id: q.session_id.clone(), anonymize: q.anonymize.unwrap_or(false), mode: q.mode.clone(), ..Default::default() };
    let (out, blocked, stats) = run(&st, move || {
        let mut s = engine.open_stream(&c, &opts)?;
        let mut out = s.push(&body);
        out.extend(s.finish());
        Ok((out, s.is_blocked(), serde_json::to_string(s.stats()).unwrap_or_default()))
    })
    .await?;
    let mut resp = (StatusCode::OK, out).into_response();
    resp.headers_mut().insert(header::CONTENT_TYPE, HeaderValue::from_static("text/event-stream"));
    resp.headers_mut().insert("x-dlp-blocked", HeaderValue::from_static(if blocked { "1" } else { "0" }));
    if let Ok(v) = HeaderValue::from_str(&stats.replace(['\n', '\r'], " ")) {
        resp.headers_mut().insert("x-dlp-stream-stats", v);
    }
    Ok(resp)
}

